function botProductReply(p, n) {
    const info = PRODUCT_INFO[p.id] || {};
    const specs = info.specs || [];
    const stock = getStock(p.id);
    const out = [];

    out.push(`<b>${p.name}</b> — <b>${fmt(p.price)} جنيه</b>`);
    if (/فيزا|بطاقه|خصم/.test(n)) {
        out.push(`بالفيزا: <b>${fmt(p.price * (1 - VISA_DISCOUNT))} جنيه</b> (خصم ${Math.round(VISA_DISCOUNT * 100)}%).`);
    }

    const asked = [];
    BOT_ATTRS.forEach(a => {
        if (a.ask.test(n)) specs.filter(([k]) => a.key.test(botNorm(k))).forEach(sp => asked.push(sp));
    });

    if (asked.length) {
        out.push(asked.map(([k, v]) => `• ${k}: ${v}`).join('<br>'));
    } else if (/ميزه|مميزات|ميزات|فيها ايه/.test(n) && info.features) {
        out.push(info.features.map(f => `• ${f}`).join('<br>'));
    } else if (!/سعر|بكام|كام|ثمن|متوفر|كميه|مخزون|اضف|ضيف|اشتري|اشتر|اطلب|احجز/.test(n) || /مواصفات|تفاصيل|معلومات/.test(n)) {
        if (info.details) out.push(info.details);
        if (specs.length) out.push(specs.slice(0, 3).map(([k, v]) => `• ${k}: ${v}`).join('<br>'));
    }

    if (/اضف|ضيف|اشتري|اشتر|اطلب|احجز/.test(n) && stock > 0) out.push('تمام ✅ ادوس «أضف للسلة» تحت.');
    if (stock <= 0) out.push('للأسف الكمية دي نفدت حالياً.');

    return { html: out.join('<br>') + botCard(p), last: p.id, chips: ['مميزات الساعة دي', 'طرق الدفع', 'التوصيل', 'سلتي'] };
}

function botCompare(list) {
    const keys = ['نوع الحركة', 'مقاومة الماء', 'قطر الهيكل', 'الحجم', 'نوع السوار', 'الخامة', 'خامة الهيكل'];
    const rows = list.map(p => {
        const sp = {};
        ((PRODUCT_INFO[p.id] || {}).specs || []).forEach(([k, v]) => { sp[k] = v; });
        const extra = keys.filter(k => sp[k]).map(k => `${k}: ${sp[k]}`).join(' / ');
        return `• <b>${p.name}</b> — ${fmt(p.price)} جنيه${extra ? '<br>&nbsp;&nbsp;' + extra : ''}`;
    }).join('<br>');
    return { html: `مقارنة سريعة:<br>${rows}${botCards(list)}` };
}

// ---------- العقل: بيحلل السؤال ويرجع الرد ----------
function botAnswer(raw) {
    const n = botNorm(raw);
    const tk = botTokens(n);
    const has = re => re.test(n);
    if (!n) return botFallback();

    // تحية / شكر / وداع
    if (tk.length <= 4 && has(/^(?:سلام|السلام|اهلا|اهلين|مرحبا|مرحبتين|هاي|هلا|هالو|هلو|صباح|مساء|hello|hi|hey)/)) {
        return { html: `أهلاً بيك في ChronoLux 👋 أنا المساعد الذكي. اسألني عن أي ساعة أو أسعار أو الدفع والتوصيل والاسترجاع.`, chips: BOT_DEFAULT_CHIPS };
    }
    if (tk.length <= 6 && has(/شكرا|تسلم|متشكر|ميرسي|thanks|thx|جزاك/)) {
        return { html: `العفو 🌟 لو احتجت أي حاجة تانية أنا موجود.`, chips: BOT_DEFAULT_CHIPS };
    }
    if (tk.length <= 4 && has(/مع السلامه|باي|وداعا|bye/)) {
        return { html: `مع السلامة! نورتنا ⌚`, chips: BOT_DEFAULT_CHIPS };
    }

    // أسئلة السياسات والمعلومات العامة
    if (has(/رقم الطلب|طلبي|طلباتي|اوردر|تتبع/)) return botOrders();
    if (has(/استرجاع|ارجاع|ارجع|رجع|استبدال|ابدل|تبديل|مرتجع|استرداد|ترجيع/)) return botReturns();
    if (has(/(?:^| )(?:ال|لل|ب|ل|وال)?(?:توصيل|شحن|ديليفري)|يوصل|توصل|مصاريف|كام يوم/)) return botDelivery();
    if (has(/تواصل|اكلم|كلمكم|اتصل|تليفون|هاتف|ارقام|رقمكم|رقم الاستفسار|واتس|ايميل|بريد|email|مدير|ضاحي|خدمه العملاء|شكوي|دعم|استفسار|(?:^| )رقم(?: |$)/)) return botContact();
    if (has(/خصوصيه|بياناتي|بياناتك|هكر|سرقه|تخزنو|بيانات البطاقه|امان الموقع|الموقع امن|امن الموقع/)) return botPrivacy();
    if (has(/ضمان|كفاله|صيانه|warranty/)) return botNotOnSite('تفاصيل الضمان');
    if (has(/اصلي|اوريجينال|اورجينال|تقليد|كوبي|original|fake/)) return botNotOnSite('المعلومة دي (أصلية المنتجات ومصدرها)');
    if (has(/مواعيد|ساعات العمل|بتفتحوا|فاتحين|مفتوح|عنوانكم|فرع|فروع|معرض|مكانكم|مقركم/)) return botNotOnSite('مواعيد العمل وعناوين الفروع');
    if (has(/داكن|دارك|ليلي|dark/)) return botTheme();
    if (has(/ازاي (?:اشتري|اطلب|اشتر|اعمل اوردر|ادفع)|طريقه (?:الشراء|الطلب)|خطوات|كيف (?:اشتري|اطلب)/)) return botHowTo();
    if (has(/سلتي|السله|سله|مشترياتي|عربيتي/)) return botCartReply();
    if (has(/من انتم|من نحن|مين انتو|مين انتم|عن المتجر|عن الموقع|نبذه|رسالتكم|رؤيتكم|اهدافكم/)) return botAbout();

    // البحث في المنتجات
    const cat = botCat(n, tk);
    const bud = botBudget(n);
    const sortMode = has(/ارخص|اقل سعر|اوفر|رخيص|اقتصادي|ادني سعر/) ? 'asc'
        : (has(/اغلي|افخم|ارقي|اعلي سعر|غالي|فاخر|بريميوم/) ? 'desc' : null);
    const content = botTokens(botKey(raw)).filter(w => w.length >= 3 && !BOT_STOP.has(w) && !BOT_NOISE_RE.test(w));
    const pool = products.filter(p =>
        (!cat || p.category === cat) &&
        (!bud || ((bud.min === undefined || p.price >= bud.min) && (bud.max === undefined || p.price <= bud.max))));

    let hits = content.length ? botScore(content, pool) : [];

    // "الساعة دي" = آخر ساعة اتكلمنا عنها
    const ctx = botCtxGet();
    if (ctx.last && !hits.some(h => h.score >= 3) && has(/(?:^| )(?:دي|ده|ديه|دا|هذه|هذا)(?: |$)|عنها|فيها|منها|نفسها|سعرها|مواصفاتها|مميزاتها|قطرها|لونها|كميتها|حجمها|خامتها|سوارها|مقاومتها/)) {
        const lp = findProduct(ctx.last);
        if (lp) hits = [{ p: lp, score: 9 }];
    }

    const wantsCompare = has(/فرق|قارن|مقارنه|ايهما|احسن ولا|افضل ولا/);
    if (wantsCompare && hits.length >= 2 && hits.length <= 3 && hits.every(h => h.score >= 3)) {
        return botCompare(hits.map(h => h.p));
    }
    if (hits.length === 1) return botProductReply(hits[0].p, n);

    const strong = hits.some(h => h.score >= 3);
    if (!strong && has(/دفع|ادفع|فيزا|visa|كاش|نقدي|عند الاستلام|بطاقه|كريدت|ماستر|تقسيط|قسط|كوبون|خصم|تخفيض|عروض/)) return botPayment();

    if (!hits.length && has(/متوفر|متاح|كميه|مخزون|نفد|نفذت|خلص|فاضل|باقي|اخر قطع/)) return botLowStock();

    // هدية / ترشيح
    const gift = has(/هديه|هدايا|اهدي|عيد ميلاد|خطوبه|جواز|تخرج/);
    const recommend = has(/رشح|اقترح|انصح|افضل|احسن|انسب|ايه المناسب/);
    if (!hits.length && (gift || recommend)) {
        if (cat) {
            const sel = botSpread(pool);
            if (!sel.length) return botFallback();
            return { html: `اخترتلك ${sel.length} ساعات من ${botCatLink(cat)} بأسعار مختلفة:${botCards(sel)}`, chips: ['أرخص ساعة', 'طرق الدفع', 'سلتي'] };
        }
        return { html: `${gift ? 'الهدية لمين؟' : 'عايز ساعة لمين؟'} قولي (رجالي / حريمي / حائط) وميزانيتك تقريباً، وأنا أرشحلك الأنسب.`, chips: ['هدية لراجل', 'هدية لست', 'ساعة حائط للبيت'] };
    }

    // قائمة منتجات (بحث بمواصفات / قسم / ميزانية / أرخص / أغلى)
    if (hits.length >= 2 || (!content.length && (cat || bud || sortMode))) {
        let list;
        let intro;
        if (hits.length >= 2) {
            list = hits.map(h => h.p);
            if (sortMode === 'asc') list.sort((a, b) => a.price - b.price);
            if (sortMode === 'desc') list.sort((a, b) => b.price - a.price);
            intro = `دي الساعات اللي لقيتها مناسبة${cat ? ' في ' + botCatLink(cat) : ''}${bud ? ' (' + botBudgetText(bud) + ')' : ''}:`;
        } else if (!pool.length) {
            const base = products.filter(p => !cat || p.category === cat).sort((a, b) => a.price - b.price);
            const cheap = base.slice(0, 2);
            return { html: `مفيش ساعات${cat ? ' ' + CATEGORY_INFO[cat].name : ''} في الحدود دي${bud ? ' (' + botBudgetText(bud) + ')' : ''}. أقرب حاجة عندنا:${botCards(cheap)}`, chips: BOT_DEFAULT_CHIPS };
        } else if (sortMode) {
            list = pool.slice().sort((a, b) => sortMode === 'asc' ? a.price - b.price : b.price - a.price);
            intro = `${sortMode === 'asc' ? 'أرخص' : 'أفخم'} الساعات${cat ? ' في ' + botCatLink(cat) : ''}${bud ? ' (' + botBudgetText(bud) + ')' : ''}:`;
        } else if (bud) {
            list = pool.slice().sort((a, b) => b.price - a.price);
            intro = `لقيت ${botCount(pool.length)}${cat ? ' في ' + botCatLink(cat) : ''} ${botBudgetText(bud)}، دي أقربهم لميزانيتك:`;
        } else {
            const s = siteCatStats(cat);
            list = botSpread(pool);
            intro = `${botCatLink(cat)}: ${s.count} موديل من ${fmt(s.min)} إلى ${fmt(s.max)} جنيه. دي 3 اختيارات بأسعار مختلفة:`;
        }
        const shown = list.slice(0, 3);
        let more = '';
        if (list.length > shown.length && !sortMode) {
            more = `<br>وفي ${botCount(list.length - shown.length)} كمان${cat ? ' — شوفهم في ' + botCatLink(cat) : ' في الصفحة الرئيسية'}.`;
        }
        return { html: intro + botCards(shown) + more, chips: ['طرق الدفع', 'التوصيل', 'سلتي'] };
    }

    // كلمات عن ساعة/منتج مش لاقيها
    if (content.length && !hits.length && (cat || bud)) {
        const sel = botSpread(pool);
        if (sel.length) return { html: `مفيش ساعة بالمواصفات دي بالظبط، بس دي الموجود${cat ? ' في ' + botCatLink(cat) : ''}:${botCards(sel)}`, chips: BOT_DEFAULT_CHIPS };
    }

    if (has(/اقسام|بتبيعو|عندكم ايه|منتجاتكم|المنتجات|تشكيله|كتالوج|ايه المتاح|الاقسام/) || (tk.length <= 3 && has(/^ساع/))) return botCategories();

    if (content.length && !hits.length && has(/ساعه|ساعات/)) {
        return { html: `مش لاقي ساعة بالاسم أو الوصف ده عندنا 🤔 جرّب تكتب اسم الماركة زي «رولكس» أو «سيكو»، أو تقولي القسم والميزانية.<br>وللاستفسار: <b dir="ltr">${BOT_PHONE}</b>.`, chips: BOT_DEFAULT_CHIPS };
    }

    return botFallback();
}

// ---------- واجهة المساعد ----------
function botSess(key, fallback) {
    try { const v = JSON.parse(sessionStorage.getItem(key)); return v === null || v === undefined ? fallback : v; } catch (e) { return fallback; }
}
function botSessSet(key, value) {
    try { sessionStorage.setItem(key, JSON.stringify(value)); } catch (e) {}
}

let botHist = [];
let botBusy = false;

function botAdd(from, html, save) {
    const box = document.getElementById('bot-msgs');
    if (!box) return null;
    const d = document.createElement('div');
    d.className = 'bot-msg ' + from;
    d.innerHTML = html;
    box.appendChild(d);
    // رد المساعد بيبدأ يتعرض من أوله، ورسالة العميل بينزل لآخرها
    box.scrollTop = from === 'bot' ? Math.max(0, d.offsetTop - 10) : box.scrollHeight;
    if (save !== false) {
        botHist.push({ f: from, h: html });
        if (botHist.length > 40) botHist = botHist.slice(-40);
        botSessSet(BOT_HIST_KEY, botHist);
    }
    return d;
}

function botSetChips(list) {
    const box = document.getElementById('bot-chips');
    if (!box) return;
    box.innerHTML = list.map(q => `<button type="button" class="bot-chip" data-q="${esc(q)}">${esc(q)}</button>`).join('');
}

function botSend(text) {
    text = String(text || '').trim().slice(0, 200);
    if (!text || botBusy) return;
    botAdd('user', esc(text));
    botBusy = true;

    const typing = botAdd('bot', '<span class="bot-typing" aria-label="المساعد بيكتب"><i></i><i></i><i></i></span>', false);
    let res;
    try { res = botAnswer(text); }
    catch (e) { res = { html: `حصلت مشكلة بسيطة عندي 😅 جرّب تسأل تاني، أو كلّمنا على <b dir="ltr">${BOT_PHONE}</b>.` }; }

    setTimeout(() => {
        if (typing) typing.remove();
        botAdd('bot', res.html);
        if (res.last) botCtxSet(res.last);
        botSetChips(res.chips || BOT_DEFAULT_CHIPS);
        botBusy = false;
    }, 450 + Math.random() * 350);
}

function botToggle(open) {
    const panel = document.getElementById('bot-panel');
    const fab = document.getElementById('bot-fab');
    if (!panel || !fab) return;
    const willOpen = open === undefined ? !panel.classList.contains('open') : open;
    panel.classList.toggle('open', willOpen);
    fab.setAttribute('aria-expanded', willOpen ? 'true' : 'false');
    botSessSet(BOT_OPEN_KEY, willOpen);
    if (willOpen) {
        const box = document.getElementById('bot-msgs');
        if (box) box.scrollTop = box.scrollHeight;
    }
}

