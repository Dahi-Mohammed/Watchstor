function botBudget(n) {
    const w = n.split(' ');
    const nums = [];
    for (let i = 0; i < w.length; i++) {
        const d = w[i].match(/^\d+/);
        if (d) {
            let v = parseInt(d[0]);
            if (w[i + 1] === 'الف' || w[i + 1] === 'الاف') { v *= 1000; i++; }
            nums.push(v);
        } else if (w[i] === 'الفين') nums.push(2000);
        else if (w[i] === 'الف') nums.push(1000);
    }
    const vals = nums.filter(v => v >= 100 && v <= 100000);
    if (!vals.length) return null;
    if (vals.length >= 2) return { min: Math.min(vals[0], vals[1]), max: Math.max(vals[0], vals[1]) };
    const over = /اكتر من|اكثر من|فوق|اعلي من|يزيد عن|ابتداء من|فاكتر/.test(n);
    return over ? { min: vals[0] } : { max: vals[0] };
}

